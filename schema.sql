DROP DATABASE IF EXISTS electronics_market;
CREATE DATABASE electronics_market CHARACTER SET utf8mb4;
USE electronics_market;

CREATE TABLE Customers (
    C_ID INT AUTO_INCREMENT PRIMARY KEY,
    C_FNAME VARCHAR(100) NOT NULL, C_NAME VARCHAR(100) NOT NULL, C_MNAME VARCHAR(100),
    C_PHONE VARCHAR(30) NOT NULL, C_EMAIL VARCHAR(254)
);
CREATE TABLE Product_Categories (
    CAT_ID INT AUTO_INCREMENT PRIMARY KEY, CAT_NAME VARCHAR(100) NOT NULL
);
CREATE TABLE Products (
    P_ID INT AUTO_INCREMENT PRIMARY KEY, P_NAME VARCHAR(200) NOT NULL,
    P_MANUFACTURER VARCHAR(100) NOT NULL, P_PRICE DECIMAL(10,2) NOT NULL,
    P_STOCK INT NOT NULL, CAT_ID INT NOT NULL
);
CREATE TABLE Orders (
    O_ID INT AUTO_INCREMENT PRIMARY KEY, C_ID INT NOT NULL, O_DATE DATE NOT NULL,
    O_STATUS VARCHAR(20) NOT NULL, O_ADDRESS VARCHAR(500)
);
CREATE TABLE Services (
    S_ID INT AUTO_INCREMENT PRIMARY KEY, S_NAME VARCHAR(200) NOT NULL, S_PRICE DECIMAL(10,2) NOT NULL
);
CREATE TABLE Order_Items (
    O_ID INT NOT NULL, P_ID INT NOT NULL, OI_QUANTITY INT NOT NULL, OI_PRICE DECIMAL(10,2) NOT NULL, PRIMARY KEY (O_ID, P_ID)
);
CREATE TABLE Order_Services (
    O_ID INT NOT NULL, S_ID INT NOT NULL, OS_DATE DATE NOT NULL, OS_COUNT INT NOT NULL, PRIMARY KEY (O_ID, S_ID)
);

